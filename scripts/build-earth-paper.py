#!/usr/bin/env python3
"""Build a local, equirectangular paper atlas from Natural Earth's public-domain land polygons.
Usage: python3 scripts/build-earth-paper.py /path/ne_110m_land.zip assets/earth-paper.svg
Only the Python standard library is required.
"""
import struct
import sys
import zipfile
from pathlib import Path


def land_rings(archive):
    with zipfile.ZipFile(archive) as source:
        data = source.read(next(name for name in source.namelist() if name.endswith('.shp')))
    if struct.unpack_from('>i', data)[0] != 9994:
        raise ValueError('Invalid shapefile header')
    offset = 100
    while offset < len(data):
        _, words = struct.unpack_from('>ii', data, offset)
        record = memoryview(data)[offset + 8:offset + 8 + words * 2]
        offset += 8 + words * 2
        shape = struct.unpack_from('<i', record)[0]
        if shape == 0:
            continue
        if shape != 5:
            raise ValueError('Only Polygon land records are supported')
        parts, points = struct.unpack_from('<ii', record, 36)
        starts = list(struct.unpack_from('<' + 'i' * parts, record, 44)) + [points]
        vertices = [struct.unpack_from('<dd', record, 44 + parts * 4 + i * 16) for i in range(points)]
        yield [vertices[starts[i]:starts[i + 1]] for i in range(parts)]


def build(archive, destination):
    paths = []
    for polygon in land_rings(archive):
        commands = []
        for ring in polygon:
            for i, (lon, lat) in enumerate(ring):
                if not -180.0001 <= lon <= 180.0001 or not -90.0001 <= lat <= 90.0001:
                    raise ValueError('Coordinate outside WGS84 bounds')
                x, y = (lon + 180) / 360 * 2048, (90 - lat) / 180 * 1024
                commands.append(f'{"M" if i == 0 else "L"}{x:.2f},{y:.2f}')
            commands.append('Z')
        paths.append('<path d="' + ''.join(commands) + '"/>')
    svg = '''<svg xmlns="http://www.w3.org/2000/svg" width="2048" height="1024" viewBox="0 0 2048 1024">
<title>Iris white relief Earth</title>
<desc>Made with Natural Earth. Public-domain ne_110m_land polygons, equirectangular projection, recolored white and grey. Generated by scripts/build-earth-paper.py.</desc>
<rect width="2048" height="1024" fill="#fafafa"/>
<g fill="#dedede" stroke="#c8c8c8" stroke-width="0.45" stroke-linejoin="round" fill-rule="evenodd">'''
    svg += ''.join(paths) + '</g></svg>\n'
    Path(destination).write_text(svg, encoding='utf-8')
    print(f'{len(paths)} land polygons → {destination}')


if __name__ == '__main__':
    build(sys.argv[1], sys.argv[2])
