const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const context={window:{}};
vm.runInNewContext(fs.readFileSync(require.resolve('../scripts/market-core.js'),'utf8'),context);
const C=context.window.IrisMarketCore;
const state={users:[{name:'甲'},{name:'乙'}],characters:[],user:0};
C.normalize(state);
const p=C.persona(state,0),other=C.persona(state,1);
const transfer=(mine,amount,extra={})=>({type:'transfer',mine,amount,currency:'CNY',status:'pending',...extra});
const outgoing=transfer(true,100.25);
C.settleTransfer(state,0,outgoing,'send');
assert.equal(p.wallet.balanceCents,878775);
C.settleTransfer(state,0,outgoing,'send');
assert.equal(p.ledger.length,1);
C.settleTransfer(state,0,outgoing,'return');
C.settleTransfer(state,0,outgoing,'return');
assert.equal(p.wallet.balanceCents,888800);
assert.equal(p.ledger.length,2);
const incoming=transfer(false,55.55);
C.settleTransfer(state,0,incoming,'accept');
C.settleTransfer(state,0,incoming,'accept');
assert.equal(p.wallet.balanceCents,894355);
assert.equal(incoming.status,'accepted');
assert.throws(()=>C.settleTransfer(state,1,incoming,'accept'),/面具/);
assert.equal(other.wallet.balanceCents,888800);
const insufficient=transfer(true,999999);
assert.throws(()=>C.settleTransfer(state,0,insufficient,'send'),/不足/);
assert.equal(insufficient.status,'pending');
const fx=transfer(false,10,{currency:'USD'});
assert.throws(()=>C.settleTransfer(state,0,fx,'accept'),/汇率/);
assert.equal(fx.status,'pending');
fx.exchangeRate=7.2;
C.settleTransfer(state,0,fx,'accept');
assert.equal(p.wallet.balanceCents,901555);
const rejected=transfer(false,99);
C.settleTransfer(state,0,rejected,'return');
assert.equal(p.wallet.balanceCents,901555);
assert.throws(()=>C.settleTransfer(state,0,rejected,'accept'),/已处理/);
const legacy=transfer(true,100);
C.settleTransfer(state,0,legacy,'return');
assert.equal(p.wallet.balanceCents,901555,'old uncharged messages must not create refunds');
const restored=JSON.parse(JSON.stringify(state));
C.settleTransfer(restored,0,JSON.parse(JSON.stringify(incoming)),'accept');
assert.equal(C.persona(restored,0).wallet.balanceCents,901555);
const product=C.product(state,'p-digital-headphone');
const order=C.createOrder(state,{userIndex:0,kind:'self',items:[{productId:product.id,specId:product.specs[0].id,quantity:1}]});
assert.equal(p.wallet.balanceCents,901555-order.totalCents);
C.refund(state,0,order.id);
assert.equal(p.wallet.balanceCents,901555);
assert.equal(p.ledger.reduce((sum,row)=>sum+row.amountCents,888800),p.wallet.balanceCents);
const app=fs.readFileSync(require.resolve('../scripts/app.js'),'utf8');
assert.match(app,/data-bank-kind="income"/);
assert.match(app,/data-bank-kind="expense"/);
assert.match(app,/最近 7 天/);
assert.match(app,/flipper.classList.toggle\('is-flipped'/);
console.log('chat-wallet: transfer settlement, isolation, FX, persistence, market sync and panel checks passed');
